// One-shot, dev-only generator (network allowed ONLY here, never in the shipped page).
// Writes src/data/tempo-calendar.json (plain) and src/data/tempo-calendar.ts.
// Usage: node scripts/gen-calendar.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FIRST = 2022;
const now = new Date();
const curStart = now.getUTCMonth() >= 8 ? now.getUTCFullYear() : now.getUTCFullYear() - 1;
const LAST = Math.max(curStart, 2026);
const LETTER = { 1: 'B', 2: 'W', 3: 'R', 0: '?' };
const COL2 = { BLEU: 'B', BLANC: 'W', ROUGE: 'R' };
const ISO = /^\d{4}-\d{2}-\d{2}$/;

const pad = (n) => String(n).padStart(2, '0');
const iso = (d) => `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())}`;
const addDay = (d) => new Date(d.getTime() + 86400000);

async function getJson(url) {
  let last;
  for (let i = 0; i < 6; i++) {
    try {
      const r = await fetch(url, { headers: { accept: 'application/json' }, signal: AbortSignal.timeout(60000) });
      if (!r.ok) throw new Error(`HTTP ${r.status} for ${url}`);
      return await r.json();
    } catch (e) { last = e; console.log(`retry ${i + 1}: ${e.message || e}`); await new Promise((r) => setTimeout(r, 5000)); }
  }
  throw last;
}

const seasons = {};
for (let y = FIRST; y <= LAST; y++) {
  const key = `${y}-${y + 1}`;
  const arr = await getJson(`https://www.api-couleur-tempo.fr/api/joursTempo?periode=${key}`);
  if (!Array.isArray(arr)) throw new Error(`${key}: not an array`);
  const map = new Map();
  for (const e of arr) {
    if (!e || typeof e !== 'object' || typeof e.dateJour !== 'string' || !ISO.test(e.dateJour) ||
        !Number.isInteger(e.codeJour) || !(e.codeJour in LETTER)) {
      throw new Error(`${key}: bad entry ${JSON.stringify(e)}`);
    }
    if (map.has(e.dateJour)) throw new Error(`${key}: duplicate ${e.dateJour}`);
    map.set(e.dateJour, LETTER[e.codeJour]);
  }
  let s = '';
  let d = new Date(Date.UTC(y, 8, 1));
  const end = new Date(Date.UTC(y + 1, 7, 31));
  for (; d <= end; d = addDay(d)) {
    const k = iso(d);
    s += map.get(k) ?? '?';
    map.delete(k);
  }
  if (map.size) throw new Error(`${key}: ${map.size} dates outside the season, e.g. ${[...map.keys()][0]}`);
  seasons[key] = s;
  console.log(key, s.length, 'days', 'B', (s.match(/B/g) || []).length, 'W', (s.match(/W/g) || []).length, 'R', (s.match(/R/g) || []).length, '?', (s.match(/\?/g) || []).length);
}

// Second source cross-check
const hist = await getJson('https://www.calendrier-tempo.fr/api/history?days=365');
if (!hist || !Array.isArray(hist.history)) throw new Error('calendrier-tempo: bad shape');
let compared = 0, agree = 0;
const disagreements = [];
for (const h of hist.history) {
  if (!h || typeof h.date !== 'string' || !ISO.test(h.date)) throw new Error(`calendrier-tempo: bad entry ${JSON.stringify(h)}`);
  const c = COL2[String(h.couleur_reelle).toUpperCase()];
  const mine = colourOf(h.date);
  if (!mine || !c) { if (mine) disagreements.push(`${h.date}: ours=${mine} other=${h.couleur_reelle}`); continue; }
  compared++;
  if (mine === c) agree++; else disagreements.push(`${h.date}: ours=${mine} other=${h.couleur_reelle}`);
}
function colourOf(date) {
  const [y, m] = date.split('-').map(Number);
  const sy = m >= 9 ? y : y - 1;
  const s = seasons[`${sy}-${sy + 1}`];
  if (!s) return null;
  const off = Math.round((Date.UTC(y, m - 1, +date.slice(8)) - Date.UTC(sy, 8, 1)) / 86400000);
  return s[off] ?? null;
}
console.log(`cross-check calendrier-tempo.fr: ${hist.history.length} entries, ${compared} compared, ${agree} agree, ${disagreements.length} disagreements`);
for (const d of disagreements) console.log('  DISAGREE', d);

mkdirSync(join(root, 'src/data'), { recursive: true });
writeFileSync(join(root, 'src/data/tempo-calendar.json'), JSON.stringify(seasons, null, 2) + '\n');
const body = Object.entries(seasons).map(([k, v]) => `  '${k}': '${v}',`).join('\n');
writeFileSync(join(root, 'src/data/tempo-calendar.ts'), `// SPDX-License-Identifier: AGPL-3.0-or-later
// SPDX-FileCopyrightText: 2026 Victor Allombert
// Generated by scripts/gen-calendar.mjs - do not edit by hand.
// Couleurs Tempo: RTE, via api-couleur-tempo.fr (relais non officiel)
// Cross-checked against calendrier-tempo.fr (CC BY 4.0) over the last 365 days.
// Each season string has one letter per day (B/W/R, ? = not known yet),
// starting on 1 September of the first year and ending on 31 August.

export const TEMPO_SEASONS: Record<string, string> = {
${body}
};

export function tempoColourOf(dateISO: string): 'B' | 'W' | 'R' | null {
  const m = /^(\\d{4})-(\\d{2})-(\\d{2})$/.exec(dateISO);
  if (!m) return null;
  const y = Number(m[1]);
  const mo = Number(m[2]);
  const d = Number(m[3]);
  const sy = mo >= 9 ? y : y - 1;
  const s = TEMPO_SEASONS[\`\${sy}-\${sy + 1}\`];
  if (s === undefined) return null;
  const off = Math.round((Date.UTC(y, mo - 1, d) - Date.UTC(sy, 8, 1)) / 86400000);
  const c = s[off];
  return c === 'B' || c === 'W' || c === 'R' ? c : null;
}
`);
console.log('wrote src/data/tempo-calendar.{json,ts}');
